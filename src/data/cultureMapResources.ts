// 获取资源类型对应的颜色
export const getResourceTypeColor = (type: ResourceType): string => {
  switch (type) {
    case "博物馆":
    case "美术馆":
      return "#b91c1c";
    case "图书馆":
    case "公共图书馆":
    case "书店":
    case "咖啡自习":
      return "#00695c";
    case "公园":
    case "文化馆":
    case "公共文化空间":
    case "文化场所":
    case "艺术表演团体":
      return "#d97706";
    case "剧场剧院":
    case "演出场所":
      return "#7c3aed";
    default:
      return "#6b7280";
  }
};

// 获取资源类型图标分类
export const getResourceCategory = (type: ResourceType): "culture" | "reading" | "public" => {
  switch (type) {
    case "博物馆":
    case "美术馆":
    case "剧场剧院":
    case "演出场所":
      return "culture";
    case "图书馆":
    case "公共图书馆":
    case "书店":
    case "咖啡自习":
      return "reading";
    case "公园":
    case "文化馆":
    case "公共文化空间":
    case "文化场所":
    case "艺术表演团体":
      return "public";
    default:
      return "public";
  }
};
